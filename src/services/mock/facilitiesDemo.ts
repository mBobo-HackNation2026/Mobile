export interface FacilitySearchResult {
  inRadius: Facility[];
  nearestOutside: Facility[];
}

export function listDemoFacilities(options: {
  type?: FacilityType | 'all';
  origin: MapOrigin;
  radiusKm?: number;
}): FacilitySearchResult {
  const origin = options.origin;
  const radius = options.radiusKm ?? 25;
  const type = options.type ?? 'all';

  const ranked = RAW_FACILITIES.map((facility) => ({
    ...facility,
    distanceKm:
      Math.round(distanceKm({ lat: origin.lat, lng: origin.lng }, facility) * 10) /
      10,
  }))
    .filter((facility) => (type === 'all' ? true : facility.type === type))
    .sort((a, b) => a.distanceKm - b.distanceKm);

  const inRadius = ranked.filter((facility) => facility.distanceKm <= radius);
  const nearestOutside =
    inRadius.length > 0
      ? []
      : ranked.filter((facility) => facility.distanceKm > radius).slice(0, 6);

  return { inRadius, nearestOutside };
}

const VERIFIED = formatISO(new Date(), { representation: 'date' });

function applyOverride(
  id: string,
  status: ChecklistStatus,
  overrides: Record<string, ChecklistStatus>,
): ChecklistStatus {
  return overrides[id] ?? status;
}

function withBucket(
  status: ChecklistStatus,
  preferred: Exclude<PlanBucket, 'done'>,
): PlanBucket {
  if (status === 'done') return 'done';
  if (status === 'pending' && preferred === 'now') return 'soon';
  return preferred;
}

/**
 * Generuje chronologiczny plan rodzica (P0 — lokalny builder, bez LLM).
 * Statusy da się nadpisać z store (checklistOverrides).
 */
export function buildParentPlan(
  profile: ParentProfile,
  overrides: Record<string, ChecklistStatus> = {},
): ParentPlan {
  const timeline = buildTimeline(profile);
  const stage = stageOrDefault(profile.stage);
  const event = profile.eventDate;
  const tasks = buildTasksForStage(profile, stage, event).map((task) => {
    const status = applyOverride(task.id, task.status, overrides);
    return {
      ...task,
      status,
      bucket: withBucket(status, task.bucket === 'done' ? 'now' : task.bucket),
    };
  });

  // Po override ponownie ustaw bucket dla done
  const normalized = tasks.map((task) => ({
    ...task,
    bucket: (task.status === 'done' ? 'done' : task.bucket) as PlanBucket,
  }));

  const open = normalized.filter((t) => t.bucket !== 'done');
  const doneCount = normalized.length - open.length;
  const dated = open
    .filter((t) => t.dueDate)
    .sort((a, b) => (a.dueDate! < b.dueDate! ? -1 : 1));

  return {
    timeline,
    tasks: normalized,
    doneCount,
    openCount: open.length,
    nextDeadline: dated[0]
      ? { title: dated[0].title, date: dated[0].dueDate! }
      : null,
    isDemo: true,
  };
}

function buildTasksForStage(
  profile: ParentProfile,
  stage: ReturnType<typeof stageOrDefault>,
  event: string | null,
): PlanTask[] {
  if (stage === 'planning') return planningTasks(profile);
  if (stage === 'after_birth' || stage === 'adoption' || stage === 'foster') {
    return afterBirthTasks(profile, event);
  }
  return pregnancyTasks(profile, event);
}

